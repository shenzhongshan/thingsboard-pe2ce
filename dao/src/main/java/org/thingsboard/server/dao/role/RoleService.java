package org.thingsboard.server.dao.role;

import org.thingsboard.server.common.data.id.RoleId;
import org.thingsboard.server.common.data.id.TenantId;
import org.thingsboard.server.common.data.page.PageData;
import org.thingsboard.server.common.data.page.PageLink;
import org.thingsboard.server.common.data.role.Role;

public interface RoleService {

    Role saveRole(TenantId tenantId, Role role);

    Role findRoleById(TenantId tenantId, RoleId roleId);

    PageData<Role> findRolesByTenantId(TenantId tenantId, PageLink pageLink);

    void deleteRole(TenantId tenantId, RoleId roleId);

    /**
     * The canonical autogenerated GROUP role granting read-only access to a shared entity group.
     * Created on first use; reused afterwards. Backs the "share read-only" shortcut.
     */
    Role findOrCreateReadOnlyEntityGroupRole(TenantId tenantId);

    /**
     * The canonical autogenerated GROUP role granting full access to a shared entity group.
     * Created on first use; reused afterwards. Backs the "share read-write" shortcut.
     */
    Role findOrCreateWriteEntityGroupRole(TenantId tenantId);

    /**
     * The canonical autogenerated GROUP role granting read-only access to a public entity group.
     * Created on first use; reused afterwards. Backs the "make public" shortcut (PE parity:
     * {@code PUBLIC_USER_ENTITY_GROUP_PERMISSIONS}).
     */
    Role findOrCreatePublicUsersEntityGroupRole(TenantId tenantId);

}
