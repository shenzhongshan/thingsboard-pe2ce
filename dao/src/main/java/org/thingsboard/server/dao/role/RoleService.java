package org.thingsboard.server.dao.role;

import org.thingsboard.server.common.data.id.CustomerId;
import org.thingsboard.server.common.data.id.RoleId;
import org.thingsboard.server.common.data.id.TenantId;
import org.thingsboard.server.common.data.page.PageData;
import org.thingsboard.server.common.data.page.PageLink;
import org.thingsboard.server.common.data.role.Role;

public interface RoleService {

    Role saveRole(TenantId tenantId, Role role);

    Role findRoleById(TenantId tenantId, RoleId roleId);

    PageData<Role> findRolesByTenantId(TenantId tenantId, PageLink pageLink);

    /**
     * Roles a customer may use: the ones it owns, plus the tenant-level ones (which are usable
     * anywhere in the tenant). Sub-customers see their own and the tenant's, not their parent's -
     * role ownership is a flat customer scope in PE, not a hierarchy.
     */
    PageData<Role> findRolesByTenantIdAndCustomerId(TenantId tenantId, CustomerId customerId, PageLink pageLink);

    /** Only the roles owned by that customer, excluding tenant-level ones. */
    PageData<Role> findRolesByCustomerId(TenantId tenantId, CustomerId customerId, PageLink pageLink);

    void deleteRolesByTenantIdAndCustomerId(TenantId tenantId, CustomerId customerId);

    void deleteRole(TenantId tenantId, RoleId roleId);

    /**
     * Deletes every role the tenant owns, in one sweep. Called from the tenant deletion path.
     * Unlike {@link #deleteRole}, it does not refuse roles that group permissions still reference —
     * the tenant's permissions are swept in the same pass, and a referencing row from another tenant
     * cannot exist.
     */
    void deleteRolesByTenantId(TenantId tenantId);

    /**
     * The canonical autogenerated GROUP role granting read-only access to a shared entity group.
     * Created on first use; reused afterwards. Backs the "share read-only" shortcut.
     */
    /** The default GENERIC role granted to every tenant administrator by the bootstrap. */
    Role findOrCreateTenantAdminRole(TenantId tenantId);

    /** The default GENERIC role granted to every customer user by the bootstrap. */
    Role findOrCreateCustomerUserRole(TenantId tenantId);

    /**
     * The default GENERIC role granted to every customer user by the bootstrap, in addition to
     * {@link #findOrCreateCustomerUserRole} — full access within their own customer's owner scope
     * (PE parity: self-service management of sub-customers, sub-users, and everything else they
     * own). Reuses the "Customer Administrator" role PE already ships with (seeded lazily by
     * {@code ensureDefaultRoles}), not a new narrower one.
     */
    Role findOrCreateCustomerAdminRole(TenantId tenantId);

    Role findOrCreateReadOnlyEntityGroupRole(TenantId tenantId);

    /**
     * The canonical autogenerated GROUP role granting full access to a shared entity group.
     * Created on first use; reused afterwards. Backs the "share read-write" shortcut.
     */
    Role findOrCreateWriteEntityGroupRole(TenantId tenantId);

    /**
     * The canonical autogenerated GROUP role granting read-only access to a public entity group.
     * Created on first use; reused afterwards. Backs the "make public" shortcut (PE parity:
     * {@code PUBLIC_USER_ENTITY_GROUP_PERMISSIONS}).
     */
    Role findOrCreatePublicUsersEntityGroupRole(TenantId tenantId);

}
